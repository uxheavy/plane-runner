#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const verifierRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const goalPath = resolve(verifierRoot, "GOAL.md");
const planPath = resolve(verifierRoot, "NON-UI-IMPLEMENTATION-PLAN.json");
const ownershipPath = resolve(verifierRoot, "ownership-map.json");
const outputPath = resolve(verifierRoot, "REQUIREMENT-COVERAGE.md");
const goal = readFileSync(goalPath, "utf8");
const plan = JSON.parse(readFileSync(planPath, "utf8"));
const ownership = JSON.parse(readFileSync(ownershipPath, "utf8"));

function section(name) {
  const match = goal.match(
    new RegExp(`^## ${name.replace(/[.*+?^${}()|[\]\\\\]/g, "\\$&")}\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, "m")
  );
  return match?.[1] ?? "";
}

function firstParagraph(text) {
  return (
    text
      .split(/\n\s*\n/)
      .map((paragraph) => paragraph.trim())
      .find(
        (paragraph) =>
          paragraph && !paragraph.startsWith("|") && !paragraph.startsWith("-") && !paragraph.startsWith("`")
      )
      ?.replaceAll("\n", " ") ?? ""
  );
}

function bulletRows(text) {
  return text
    .split("\n")
    .filter((line) => line.startsWith("- "))
    .map((line) => line.slice(2).trim());
}

function numberedRows(text) {
  return text
    .split("\n")
    .filter((line) => /^\d+\. /.test(line))
    .map((line) => line.replace(/^\d+\. /, "").trim());
}

function gateRows() {
  return [...goal.matchAll(/^### (G[0-5]) — (.+)$/gm)].map(([_, id, name]) => ({ id, name }));
}

function phaseRows() {
  return [...goal.matchAll(/^\| (P(?:[0-9]|1[01]))\s+\|\s+([^|]+)\|\s+([^|]+)\|\s+([^|]+)\|\s+([^|]+)\|/gm)].map(
    ([_, id, outcome, dependencies, lanes, integrator]) => ({
      id,
      outcome: outcome.trim(),
      dependencies: dependencies.trim(),
      lanes: lanes.trim(),
      integrator: integrator.trim(),
    })
  );
}

const invariantRows = bulletRows(section("Normative invariants"));
const completionRows = numberedRows(section("Completion proof"));
const gates = gateRows();
const phases = phaseRows();
const laneByPhase = new Map(plan.lanes.map((lane) => [`P${lane.id.slice(1)}`, lane]));
const surfacesByLane = new Map();
for (const surface of ownership.surfaces) {
  for (const laneId of surface.planLaneIds) {
    const phaseId = `P${laneId.slice(1)}`;
    const rows = surfacesByLane.get(phaseId) ?? [];
    rows.push(surface.surfaceId);
    surfacesByLane.set(phaseId, rows);
  }
}

function markdownTable(headers, rows) {
  const widths = headers.map((header, index) => Math.max(3, header.length, ...rows.map((row) => row[index].length)));
  const formatRow = (row) =>
    `| ${row.map((cell, index) => `${cell}${" ".repeat(widths[index] - cell.length)}`).join(" | ")} |`;
  return [
    formatRow(headers),
    `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`,
    ...rows.map(formatRow),
  ].join("\n");
}

function render() {
  const lines = [
    "<!-- Generated by verifiers/render-requirement-coverage.mjs from GOAL.md, NON-UI-IMPLEMENTATION-PLAN.json, and ownership-map.json. Do not edit by hand. -->",
    "",
    "# Plane Agent Tooling Requirement Coverage",
    "",
    "## Authority",
    "",
    "This generated map proves coverage of the current durable GOAL. It is evidence, not a competing approval or freeze prerequisite. The sole G0 human approval is the exact statement in `APPROVAL-MANIFEST.md`; generated schemas are a G1 gate and production qualification is G4.",
    "",
    "## Sources",
    "",
    "- `GOAL.md` outcome, normative product invariants, G0–G5 gates, P0–P11 phases, and completion proof.",
    "- `NON-UI-IMPLEMENTATION-PLAN.json` lane owners, gate windows, and lane evidence.",
    "- `ownership-map.json` schema-backed writable surfaces and root-integrator joins.",
    "- `RELEASE-MANIFEST.md`, `VERIFICATION-MANIFEST.md`, and `EVALUATION-SCENARIOS.md` remain later evidence inputs; they do not authorize or freeze G0.",
    "",
    "## Outcome",
    "",
    firstParagraph(section("Observable outcome and audience")),
    "",
    "## Normative product invariants",
    "",
    markdownTable(
      ["ID", "GOAL invariant", "Covered by"],
      invariantRows.map((row, index) => [
        `GOAL-INV-${String(index + 1).padStart(2, "0")}`,
        row,
        "GOAL.md normative invariants; applicable P0–P11 and G0–G5 evidence",
      ])
    ),
    "",
    "## Integration gates",
    "",
    markdownTable(
      ["Gate", "Durable gate name", "Covered by"],
      gates.map((gate) => [gate.id, gate.name, "GOAL.md gate definition and generated plan evidence"])
    ),
    "",
    "## P0–P11 phase and writable-surface join",
    "",
    markdownTable(
      ["Phase", "Plan lane", "Outcome", "Lane owner", "Gate/integrator", "Owned writable surfaces"],
      phases.map((phase) => {
        const lane = laneByPhase.get(phase.id);
        const surfaces = surfacesByLane.get(phase.id)?.toSorted().join(", ") ?? "none";
        return [phase.id, lane?.id ?? "missing", phase.outcome, lane?.owner ?? "missing", phase.integrator, surfaces];
      })
    ),
    "",
    "## Completion proof",
    "",
    "Every completion-proof row is copied from the current GOAL and remains unsatisfied until its named verifier and evidence are recorded at the applicable gate.",
    "",
    ...completionRows.map((row, index) => `- **GOAL-PROOF-${String(index + 1).padStart(2, "0")}:** ${row}`),
    "",
    "## Gate ownership rule",
    "",
    "A lane or writable surface is covered only when the machine-readable ownership map gives it exactly one writer (except multiple surfaces intentionally owned by the same root integrator) and the verifier reports no cross-owner ancestor/descendant overlap.",
    "",
  ];
  return lines.join("\n");
}

const rendered = render();
const mode = process.argv[2] ?? "--check";
if (mode === "--write") {
  writeFileSync(outputPath, rendered);
  console.log(`wrote ${outputPath}`);
} else if (mode === "--check") {
  if (readFileSync(outputPath, "utf8") !== rendered) {
    console.error("REQUIREMENT-COVERAGE.md is stale. Run this script with --write.");
    process.exit(1);
  }
  console.log("requirement coverage is current and deterministically generated");
} else {
  console.error("usage: render-requirement-coverage.mjs --write|--check");
  process.exit(2);
}
